-- player as a gnome in the player's own armor: cheerful, cheeky, proud of
-- being small, a little vain about how well the two of them match, and
-- sure that gnomes invented most things. Each key is a moment
-- (Core/Reactions.lua). Lines are drawn like cards from a shuffled deck, so
-- none comes back until the rest of its pile has been said.
--
-- A line is a string, or a table for a line with its own touches:
--
--   { "text", anim = 69, tone = "[excited]", time = "night", zone = "Westfall",
--     class = "MAGE", min = 50, max = 20, after = 3600 }
--
--   anim    the emote it plays with (Data/Moves.lua IDs), instead of the
--           moment's own
--   tone    how a recording delivers it, as Eleven v3 emotion tags
--           ("[sniffles]"); only tools/voice/generate.py reads it
--   say     for a line with fill-ins: what its recording says instead, the
--           same line without them ("Level {level}!" is recorded as "Level
--           up!"); the bubble still shows the full line
--   time    only "morning" (5-11), "afternoon" (11-17), "evening" (17-22)
--           or "night" (22-5), by the computer's clock
--   zone    only in that zone (as the zone text reads)
--   class   only for that class (UnitClass's token: "MAGE", "WARRIOR"...)
--   min,max only at or above / at or below that player level
--   after   only once the session has run that many seconds
--
-- Tokens filled in: {name} the player, {zone}, {level}, {class} and {race}
-- (the player's), {friend} and {tier} (a friendship line's NPC and its tier
